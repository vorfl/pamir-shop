/** Данные запуска из LaunchData.gs — чтобы тесты сверялись с тем же, что уйдёт в Google. */
function launchData() {
  const sb = {};
  vm.createContext(sb);
  vm.runInContext(fs.readFileSync(path.join(DIR, 'LaunchData.gs'), 'utf8'), sb);
  return { products: sb.LAUNCH_PRODUCTS, recipes: sb.LAUNCH_RECIPES, settings: sb.LAUNCH_SETTINGS, brands: sb.LAUNCH_BRANDS, del: sb.LAUNCH_DELETE_IDS };
}

