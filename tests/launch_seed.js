/** «Нажать всё»: резервная копия и «Застосувати» до конца. Возвращает число нажатий. */
function applyAll(g, opts) {
  g.call('launchBackup_');
  let n = 0, res;
  do { res = g.call('launchApply_', opts || {}); n++; if (!res.ok) throw new Error('launch: ' + JSON.stringify(res)); } while (!res.done && n < 200);
  if (!res.done) throw new Error('launch: не дошло до конца');
  g.clearCache();
  return n;
}

